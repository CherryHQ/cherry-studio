const officialTags: Record<string, string[]> = tags
const searchText = new Map(
  iconNames.map((name) => {
    const english = officialTags[name] ?? []
    return [name, [name, ...english, ...english.flatMap((tag) => chineseKeywords[tag] ?? [])].join(' ').toLowerCase()]
  })
)

export const searchSelectionIcons = (query: string): typeof iconNames => {
  const normalized = query.trim().toLowerCase()
  return normalized ? iconNames.filter((name) => searchText.get(name)?.includes(normalized)) : iconNames
}
