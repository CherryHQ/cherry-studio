import { useEffect, useRef, useState } from 'react'
import { useTranslation } from 'react-i18next'

import {
  Button,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  Textarea
} from '@cherrystudio/ui'
import type { AddNewTopicPayload } from '@renderer/components/composer/variants/shared/composerProviderActions'
import { ipcApi } from '@renderer/ipc'
import type { UniqueModelId } from '@shared/data/types/model'

interface Props {
  sessionId: string
  modelId?: UniqueModelId
  hasMessages: boolean
  percentage?: number | null
  assistantId?: string
  onNewTopic?: (payload?: AddNewTopicPayload) => void | Promise<void>
}

/** Generation and export are separate explicit user actions. Nothing is generated by the offer. */
export function ConversationHandoff({ sessionId, modelId, hasMessages, percentage, assistantId, onNewTopic }: Props) {
  const { t } = useTranslation()
  const [open, setOpen] = useState(false)
  const [draft, setDraft] = useState('')
  const [error, setError] = useState(false)
  const [busy, setBusy] = useState(false)
  const [dismissed, setDismissed] = useState(false)
  const request = useRef<string | undefined>(undefined)
  const generation = useRef(0)
  const cancel = () => {
    generation.current += 1
    if (request.current) void ipcApi.request('ai.text.abort', { requestId: request.current }).catch(() => undefined)
    request.current = undefined
    setBusy(false)
    setOpen(false)
    setDraft('')
    setError(false)
  }
  useEffect(() => {
    setDismissed(false)
    setOpen(false)
    setDraft('')
    setBusy(false)
    setError(false)
    return () => {
      generation.current += 1
      if (request.current) void ipcApi.request('ai.text.abort', { requestId: request.current }).catch(() => undefined)
      request.current = undefined
    }
  }, [sessionId])

  if (!hasMessages) return null
  const generate = async () => {
    if (!modelId || busy) return
    const revision = ++generation.current
    const requestId = crypto.randomUUID()
    request.current = requestId
    setBusy(true)
    setError(false)
    try {
      const result = await ipcApi.request('ai.handoff.generate', { sessionId, modelId, requestId })
      if (generation.current === revision) setDraft(result)
    } catch {
      if (generation.current === revision) setError(true)
    } finally {
      if (generation.current === revision) {
        setBusy(false)
        request.current = undefined
      }
    }
  }
  const startNew = async () => {
    if (!onNewTopic || busy || !draft.trim()) return
    const fileTokenSourceId = crypto.randomUUID()
    const blob = new Blob([draft], { type: 'text/markdown' })
    setBusy(true)
    try {
      await onNewTopic({
        assistantId,
        handoffDraft: {
          text: '',
          tokens: [
            { id: `file:${fileTokenSourceId}`, kind: 'file', label: 'conversation-handoff.md', index: 0, textOffset: 0 }
          ],
          files: [
            {
              fileTokenSourceId,
              blob,
              name: 'conversation-handoff',
              origin_name: 'conversation-handoff.md',
              ext: '.md',
              size: blob.size,
              type: 'text'
            }
          ],
          knowledgeBaseIds: [],
          mentionedModelIds: [],
          modelMultiSelectMode: false
        }
      })
      cancel()
    } catch {
      setError(true)
      setBusy(false)
    }
  }
  const offer = !dismissed && percentage != null && percentage >= 80
  return (
    <>
      <div className="flex items-center justify-end gap-2 px-4 py-1">
        {offer ? (
          <p role="status" className="mr-auto text-xs text-muted-foreground">
            {t('handoff.offer')}
          </p>
        ) : null}
        <Button
          variant="ghost"
          size="sm"
          disabled={!modelId}
          onClick={() => {
            setOpen(true)
            setDismissed(true)
          }}>
          {t('handoff.create')}
        </Button>
        {offer ? (
          <Button variant="ghost" size="sm" onClick={() => setDismissed(true)}>
            {t('common.close')}
          </Button>
        ) : null}
      </div>
      <Dialog
        open={open}
        onOpenChange={(next) => {
          if (!next) cancel()
        }}>
        <DialogContent size="lg" className="flex max-h-[85vh] flex-col">
          <DialogHeader>
            <DialogTitle>{t('handoff.create')}</DialogTitle>
            <DialogDescription>{t('handoff.disclosure')}</DialogDescription>
          </DialogHeader>
          {error ? (
            <p role="alert" className="text-sm text-destructive">
              {t('handoff.error')}
            </p>
          ) : null}
          {draft ? (
            <Textarea.Input
              aria-label={t('handoff.draft')}
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              className="min-h-48 flex-1 overflow-y-auto font-mono text-sm"
            />
          ) : (
            <p className="text-sm text-muted-foreground">{t('handoff.sections')}</p>
          )}
          <DialogFooter>
            <Button variant="outline" onClick={cancel}>
              {t('common.cancel')}
            </Button>
            <Button variant="outline" disabled={busy || !modelId} onClick={() => void generate()}>
              {busy ? t('common.loading') : draft ? t('handoff.regenerate') : t('handoff.generate')}
            </Button>
            {onNewTopic ? (
              <Button disabled={busy || !draft.trim()} onClick={() => void startNew()}>
                {t('handoff.new')}
              </Button>
            ) : null}
            <Button
              disabled={busy || !draft.trim()}
              onClick={() => {
                void window.api.file.save('conversation-handoff.md', draft).catch(() => setError(true))
              }}>
              {t('handoff.save')}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  )
}
