import { useEffect, useRef, useState } from 'react'
import { useTranslation } from 'react-i18next'

import {
  Button,
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
  SelectDropdown,
  Textarea
} from '@cherrystudio/ui'
import type { AddNewTopicPayload } from '@renderer/components/composer/variants/shared/composerProviderActions'
import { getProviderDisplayName, useProviders } from '@renderer/hooks/useProvider'
import { ipcApi } from '@renderer/ipc'
import { getProviderDisplayNameById } from '@renderer/utils/naming'
import type { Model, UniqueModelId } from '@shared/data/types/model'

interface Props {
  sessionId: string
  modelId?: UniqueModelId
  /** Composer models when several are selected; the user picks one for generation. */
  modelCandidates?: Model[]
  hasMessages: boolean
  percentage?: number | null
  assistantId?: string
  onNewTopic?: (payload?: AddNewTopicPayload) => void | Promise<void>
}

// Dismissal outlives the keyed component: navigating away and back remounts
// the handoff, and a dismissed offer must not reappear for the same session.
const dismissedSessions = new Set<string>()

/** Generation and export are separate explicit user actions. Nothing is generated by the offer. */
export function ConversationHandoff({
  sessionId,
  modelId,
  modelCandidates,
  hasMessages,
  percentage,
  assistantId,
  onNewTopic
}: Props) {
  const { t } = useTranslation()
  const { providers } = useProviders()
  const modelLabel = (model: Model) => {
    const provider = providers.find((item) => item.id === model.providerId)
    return `${model.name} | ${getProviderDisplayName(provider) || getProviderDisplayNameById(model.providerId)}`
  }
  const [open, setOpen] = useState(false)
  const [draft, setDraft] = useState('')
  const [error, setError] = useState(false)
  const [busy, setBusy] = useState(false)
  // Explicit user choice when the composer has several models; modelId covers the single-model case.
  const [chosenModelId, setChosenModelId] = useState<UniqueModelId | undefined>(undefined)
  const chosenModel = modelCandidates?.find((model) => model.id === chosenModelId)
  const effectiveModelId = modelId ?? (modelCandidates?.length === 1 ? modelCandidates[0].id : chosenModel?.id)
  const [dismissed, setDismissedState] = useState(() => dismissedSessions.has(sessionId))
  const dismiss = () => {
    dismissedSessions.add(sessionId)
    setDismissedState(true)
  }
  const request = useRef<string | undefined>(undefined)
  const generation = useRef(0)
  const cancel = () => {
    generation.current += 1
    if (request.current) void ipcApi.request('ai.text.abort', { requestId: request.current }).catch(() => undefined)
    request.current = undefined
    setBusy(false)
    setOpen(false)
    setDraft('')
    setError(false)
  }
  useEffect(() => {
    setDismissedState(dismissedSessions.has(sessionId))
    setOpen(false)
    setDraft('')
    setBusy(false)
    setError(false)
    setChosenModelId(undefined)
    return () => {
      generation.current += 1
      if (request.current) void ipcApi.request('ai.text.abort', { requestId: request.current }).catch(() => undefined)
      request.current = undefined
    }
  }, [sessionId])

  if (!hasMessages) return null
  const generate = async () => {
    if (!effectiveModelId || busy) return
    const revision = ++generation.current
    const requestId = crypto.randomUUID()
    request.current = requestId
    setBusy(true)
    setError(false)
    try {
      const result = await ipcApi.request('ai.handoff.generate', { sessionId, modelId: effectiveModelId, requestId })
      if (generation.current === revision) setDraft(result)
    } catch {
      if (generation.current === revision) setError(true)
    } finally {
      if (generation.current === revision) {
        setBusy(false)
        request.current = undefined
      }
    }
  }
  const startNew = async () => {
    if (!onNewTopic || busy || !draft.trim()) return
    const fileTokenSourceId = crypto.randomUUID()
    const blob = new Blob([draft], { type: 'text/markdown' })
    setBusy(true)
    try {
      await onNewTopic({
        // Explicit null keeps a handoff from an unlinked topic unlinked;
        // undefined would let the new-topic resolver pick an assistant.
        assistantId: assistantId ?? null,
        handoffDraft: {
          text: '',
          tokens: [
            { id: `file:${fileTokenSourceId}`, kind: 'file', label: 'conversation-handoff.md', index: 0, textOffset: 0 }
          ],
          files: [
            {
              fileTokenSourceId,
              blob,
              name: 'conversation-handoff',
              origin_name: 'conversation-handoff.md',
              ext: '.md',
              size: blob.size,
              type: 'text'
            }
          ],
          knowledgeBaseIds: [],
          mentionedModelIds: [],
          modelMultiSelectMode: false
        }
      })
      cancel()
    } catch {
      setError(true)
      setBusy(false)
    }
  }
  const offer = !dismissed && percentage != null && percentage >= 80
  // With several composer models there is no single resolved model; the dialog picker decides.
  const needsModelChoice = !modelId && (modelCandidates?.length ?? 0) > 1
  const canOpen = Boolean(modelId) || (modelCandidates?.length ?? 0) > 0
  return (
    <>
      <div className="flex items-center justify-end gap-2 px-4 py-1">
        {offer ? (
          <p role="status" className="mr-auto text-xs text-muted-foreground">
            {t('handoff.offer')}
          </p>
        ) : null}
        <Button
          variant="ghost"
          size="sm"
          disabled={!canOpen}
          onClick={() => {
            setOpen(true)
            dismiss()
          }}>
          {t('handoff.create')}
        </Button>
        {offer ? (
          <Button variant="ghost" size="sm" onClick={dismiss}>
            {t('common.close')}
          </Button>
        ) : null}
      </div>
      <Dialog
        open={open}
        onOpenChange={(next) => {
          if (!next) cancel()
        }}>
        <DialogContent size="lg" className="flex max-h-[85vh] flex-col">
          <DialogHeader>
            <DialogTitle>{t('handoff.create')}</DialogTitle>
            <DialogDescription>{t('handoff.disclosure')}</DialogDescription>
          </DialogHeader>
          {error ? (
            <p role="alert" className="text-sm text-destructive">
              {t('handoff.error')}
            </p>
          ) : null}
          {needsModelChoice && modelCandidates ? (
            <SelectDropdown
              items={modelCandidates}
              selectedId={chosenModelId ?? null}
              onSelect={(id) => setChosenModelId(id as UniqueModelId)}
              placeholder={t('handoff.model')}
              emptyText={t('handoff.model')}
              renderSelected={modelLabel}
              renderItem={modelLabel}
            />
          ) : null}
          {draft ? (
            <Textarea.Input
              aria-label={t('handoff.draft')}
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              className="min-h-48 flex-1 overflow-y-auto font-mono text-sm"
            />
          ) : (
            <p className="text-sm text-muted-foreground">{t('handoff.sections')}</p>
          )}
          <DialogFooter>
            <Button variant="outline" onClick={cancel}>
              {t('common.cancel')}
            </Button>
            <Button variant="outline" disabled={busy || !effectiveModelId} onClick={() => void generate()}>
              {busy ? t('common.loading') : draft ? t('handoff.regenerate') : t('handoff.generate')}
            </Button>
            {onNewTopic ? (
              <Button disabled={busy || !draft.trim()} onClick={() => void startNew()}>
                {t('handoff.new')}
              </Button>
            ) : null}
            <Button
              disabled={busy || !draft.trim()}
              onClick={() => {
                void window.api.file.save('conversation-handoff.md', draft).catch(() => setError(true))
              }}>
              {t('handoff.save')}
            </Button>
          </DialogFooter>
        </DialogContent>
      </Dialog>
    </>
  )
}
