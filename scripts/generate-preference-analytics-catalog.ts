/**
 * Generates `src/main/services/analyticsPreferenceCatalog.gen.ts`: the value kind of every Preference key, read from
 * the `PreferenceSchemas` types. Product analytics reports a setting's value only when the catalog says it is a
 * boolean, a number, or one of fixed string options; any other string is free text and reports set or not set.
 *
 * Run via `pnpm gen:preference-analytics-catalog`. A main-process test fails when the committed file is stale.
 */

import { execFileSync } from 'child_process'
import * as fs from 'fs'
import * as path from 'path'

import ts from 'typescript'

const ROOT_DIR = path.join(__dirname, '..')
const SCHEMA_FILE = path.join(ROOT_DIR, 'src', 'shared', 'data', 'preference', 'preferenceSchemas.ts')
const OUTPUT_FILE = path.join(ROOT_DIR, 'src', 'main', 'services', 'analyticsPreferenceCatalog.gen.ts')

type Kind = 'bool' | 'num' | 'text' | string[]

function kindOf(type: ts.Type): Kind | null {
  const parts = (type.isUnion() ? type.types : [type]).filter(
    (part) => !(part.flags & (ts.TypeFlags.Null | ts.TypeFlags.Undefined))
  )
  if (parts.length === 0) return null
  if (parts.every((part) => part.flags & ts.TypeFlags.BooleanLike)) return 'bool'
  if (parts.every((part) => part.flags & ts.TypeFlags.NumberLike)) return 'num'
  if (parts.every((part) => part.isStringLiteral())) {
    return parts.map((part) => part.value).sort()
  }
  if (parts.every((part) => part.flags & ts.TypeFlags.StringLike)) return 'text'
  return null
}

/** Each Preference key's value kind; keys whose type is an object, array, or mixed union are left out. */
export function readPreferenceAnalyticsKinds(): Record<string, Kind> {
  const config = ts.getParsedCommandLineOfConfigFile(
    path.join(ROOT_DIR, 'tsconfig.node.json'),
    {},
    {
      ...ts.sys,
      onUnRecoverableConfigFileDiagnostic: (diagnostic) => {
        throw new Error(ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
      }
    }
  )
  const program = ts.createProgram([SCHEMA_FILE], { ...config!.options, noEmit: true })
  const checker = program.getTypeChecker()
  const source = program.getSourceFile(SCHEMA_FILE)!
  const schemas = source.statements.find(
    (node): node is ts.InterfaceDeclaration => ts.isInterfaceDeclaration(node) && node.name.text === 'PreferenceSchemas'
  )
  if (!schemas) throw new Error('PreferenceSchemas interface not found')
  const defaults = checker.getTypeAtLocation(schemas).getProperty('default')!
  const entries = checker
    .getTypeOfSymbolAtLocation(defaults, schemas)
    .getProperties()
    .map((property) => [property.name, kindOf(checker.getTypeOfSymbolAtLocation(property, schemas))] as const)
    .filter((entry): entry is readonly [string, Kind] => entry[1] !== null)
    .sort(([a], [b]) => a.localeCompare(b))
  return Object.fromEntries(entries)
}

function buildSource(kinds: Record<string, Kind>): string {
  const format = (kind: Kind) =>
    Array.isArray(kind) ? `[${kind.map((value) => `'${value}'`).join(', ')}]` : `'${kind}'`
  const lines = Object.entries(kinds).map(([key, kind]) => `  '${key}': ${format(kind)},`)
  return [
    '// Generated by scripts/generate-preference-analytics-catalog.ts from PreferenceSchemas. Do not edit.',
    '',
    "/** 'text' values are free text and never leave the device; fixed options are listed. */",
    "export type PreferenceAnalyticsKind = 'bool' | 'num' | 'text' | readonly string[]",
    '',
    'export const PREFERENCE_ANALYTICS_CATALOG: Readonly<Record<string, PreferenceAnalyticsKind>> = {',
    ...lines,
    '}',
    ''
  ].join('\n')
}

if (require.main === module) {
  fs.writeFileSync(OUTPUT_FILE, buildSource(readPreferenceAnalyticsKinds()))
  execFileSync('pnpm', ['exec', 'oxfmt', '--write', OUTPUT_FILE], { cwd: ROOT_DIR, stdio: 'ignore' })
  console.log(`Wrote ${path.relative(ROOT_DIR, OUTPUT_FILE)}`)
}
