const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { DatabaseSync } = require('node:sqlite')

const fixture = path.resolve(process.argv[2])
const expected = require('./seed-evidence.json').expected
const database = path.join(fixture, 'data', 'Data', 'cherrystudio.sqlite')
assert(fs.existsSync(database))
const db = new DatabaseSync(database, { readOnly: true })
try {
  const migration = JSON.parse(db.prepare('SELECT value FROM app_state WHERE key = ?').get('migration_v2_status').value)
  assert.equal(migration.status, 'completed')
  assert.equal(migration.migratedFromV1, true)
  const assistant = db.prepare('SELECT id, name, prompt FROM assistant WHERE id = ?').get(expected.assistantId)
  assert.equal(assistant?.name, expected.assistantName)
  assert.equal(assistant.prompt, expected.prompt)
  const topic = db.prepare('SELECT id, name, assistant_id FROM topic WHERE id = ?').get(expected.topicId)
  assert.equal(topic?.name, expected.topicName)
  assert.equal(topic.assistant_id, expected.assistantId)
  const message = db.prepare('SELECT id, topic_id, role, parent_id, data FROM message WHERE id = ?')
  const user = message.get(expected.userId)
  const reply = message.get(expected.replyId)
  assert.equal(user?.topic_id, topic.id)
  assert.equal(reply?.topic_id, topic.id)
  assert.equal(user.role, 'user')
  assert.equal(reply.role, 'assistant')
  assert.equal(reply.parent_id, user.id)
  const root = message.get(user.parent_id)
  assert.equal(root?.topic_id, topic.id)
  assert.equal(root.role, 'root')
  assert.equal(root.parent_id, null)
  assert(user.data.includes(expected.userText), user.data)
  assert(reply.data.includes(expected.replyText), reply.data)
  const integrity = Object.values(db.prepare('PRAGMA integrity_check').get())[0]
  assert.equal(integrity, 'ok')
  const foreignKeyViolations = db.prepare('PRAGMA foreign_key_check').all()
  assert.equal(foreignKeyViolations.length, 0)
  const evidence = { database, migration, assistant, topic, root, user, reply, integrity, foreignKeyViolations }
  if (process.argv[3]) fs.writeFileSync(process.argv[3], JSON.stringify(evidence, null, 2))
  console.log(JSON.stringify(evidence, null, 2))
} finally {
  db.close()
}
